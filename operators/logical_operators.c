# include<stdio.h>
int main(){
    printf("\n ----Lets try some logical operators\n---");
    int h=0 , j=1;

    // Lets check some logical operators here
    printf("The and logical operator result is %d\n",h && j);
    printf("The or logical operator result is %d\n",h || j);
    printf("The not logical operator result is %d\n",!j);
    printf("The not logical operator result is %d\n",!h);

    return 0;


}