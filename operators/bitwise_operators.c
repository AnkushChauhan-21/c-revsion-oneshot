# include<stdio.h>
int main(){
    printf("\n---- Lets explore some bitwise operators-----\n");
 int A = 60 , B=14;


    printf("The and Bitwise operator result is %d\n", A&B);
    printf("The or Bitwise operator result is %d\n",A|B);
    printf("The xor Bitwise operator result is %d\n",A^B);
    printf("The ones Bitwise operator result is %d\n",~B);
    printf("The left shift Bitwise operator result is %d\n",A<<B);
    printf("The right shift Bitwise operator result is %d\n",A>>B);


  return 0;
}


